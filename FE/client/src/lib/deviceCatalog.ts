/** Marcas sugeridas conforme o tipo de aparelho. */
export function brandsForType(productType: string): string[] {
  return DEVICE_BRANDS_BY_TYPE[productType] ?? DEVICE_BRANDS_BY_TYPE.Outro ?? [];
}

/** Modelos sugeridos pela marca (e filtrados pelo tipo quando possível). */
export function modelsForBrand(productType: string, brand: string): string[] {
  const key = brand.trim();
  if (!key) return [];
  const all = DEVICE_MODELS_BY_BRAND[key] ?? [];
  const t = productType.toLowerCase();

  if (t.includes("tablet") || t.includes("ipad")) {
    const tablets = all.filter(m =>
      /ipad|tab\b|tab |pad\b|pad |tablet|fire hd|fire max|fire 7|tl\d|ypy|vision tab/i.test(m)
    );
    return tablets.length ? tablets : all;
  }
  if (t.includes("watch") || t.includes("smartwatch")) {
    const watches = all.filter(m => /watch|bip|gts|gtr|forerunner|venu|fenix|ignite|vantage|pacer|active/i.test(m));
    return watches.length ? watches : all;
  }
  if (t.includes("fone") || t.includes("airpods") || t.includes("buds")) {
    const audio = all.filter(m =>
      /airpods|buds|tune|wave|wf-|wh-|quantum|soundcore|bowie|encok|melobuds|t13|t20/i.test(m)
    );
    return audio.length ? audio : all;
  }
  if (t.includes("notebook") || t.includes("laptop")) {
    const notebooks = all.filter(m =>
      /inspiron|vostro|xps|latitude|pavilion|victus|elitebook|probook|ideapad|thinkpad|legion|aspire|nitro|swift|vivobook|zenbook|fe1|a52|a62|storm|master/i.test(
        m
      )
    );
    return notebooks.length ? notebooks : all;
  }

  // Smartphone: exclui tablet / watch / áudio quando houver alternativas
  const phones = all.filter(
    m =>
      !/ipad|tab\b|tab |pad\b|pad |tablet|fire hd|fire max|watch|airpods|buds|tune|wave|wf-|wh-|bip |gts |gtr |forerunner|venu|fenix|soundcore|bowie|inspiron|vostro|xps|pavilion|ideapad|thinkpad|aspire|vivobook|zenbook|elitebook|probook|victus|nitro|swift|fe1|ypy|vision tab|tl\d/i.test(
        m
      )
  );
  return phones.length ? phones : all;
}
